-- 질문 은행(08 설계 3장 "질문"). 질문 글은 questions, 채점 기준·모범 답안·링크는 서버 전용 question_keys.
-- 은행 질문의 id는 콘텐츠 파일에서 직접 정한다(화면의 Q.042). 프로젝트 질문은 #39에서 project_id와 함께 더한다.
create table public.questions (
  id int generated by default as identity primary key,
  topic_id text not null references public.topics (id),
  level text not null check (level in ('basic', 'mid', 'deep')),
  prompt text not null check (char_length(prompt) between 5 and 300),
  is_hidden boolean not null default false,
  trial_field text check (trial_field in ('cs', 'backend', 'frontend'))
);

create index questions_topic_level on public.questions (topic_id, level) where not is_hidden;

create table public.question_keys (
  question_id int primary key references public.questions (id) on delete cascade,
  rubric jsonb not null,
  model_answer text not null,
  links jsonb
);

-- 둘 다 RLS를 켜고 읽기 정책을 두지 않는다. questions의 "내 세션·복습·북마크의 질문만" 정책은
-- 그 테이블이 생기는 #30에서 더한다. 그전까지 질문은 서버(service_role)만 읽는다.
alter table public.questions enable row level security;
alter table public.question_keys enable row level security;

-- 출제 후보: 숨기지 않은 은행 질문 + 분야. security_invoker라 RLS를 그대로 따른다(브라우저는 못 읽는다).
create view public.bank_questions
with (security_invoker = true) as
select q.id, q.topic_id, t.field, q.level, q.prompt, q.trial_field
from public.questions q
join public.topics t on t.id = q.topic_id
where not q.is_hidden;

revoke all on public.bank_questions from anon, authenticated;

-- 콘텐츠를 넣은 뒤 id 시퀀스를 은행 최대값 뒤로 맞춘다(새로 생기는 프로젝트 질문이 그 뒤 번호를 쓴다)
create function public.sync_question_id_seq()
returns void
language sql
security definer
set search_path = ''
as $$
  select setval(
    pg_get_serial_sequence('public.questions', 'id'),
    greatest((select max(id) from public.questions), 1)
  );
$$;

revoke execute on function public.sync_question_id_seq() from public, anon, authenticated;
grant execute on function public.sync_question_id_seq() to service_role;
